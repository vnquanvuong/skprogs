  !> Returns the Yukawa exponents alpha_i = beta_i*omega and coefficients c_i for an mreq-term
  !! erf/erfc range-separation expansion at range-separation parameter omega. mreq is clamped to
  !! [1, erfYukawaMaxM]; nYukawa (<= mreq) is the number of valid entries written to alphas/coeffs.
  subroutine getErfRangeSepYukawas(mreq, omega, nYukawa, alphas, coeffs)

    !> requested number of Yukawa terms
    integer, intent(in) :: mreq

    !> range-separation parameter
    real(dp), intent(in) :: omega

    !> number of Yukawa terms actually returned
    integer, intent(out) :: nYukawa

    !> Yukawa exponents alpha_i = beta_i*omega
    real(dp), intent(out) :: alphas(:)

    !> Yukawa coefficients c_i (sum_i c_i = 1)
    real(dp), intent(out) :: coeffs(:)

    !! clamped term count
    integer :: mm

    call initErfYukawa()

    mm = mreq
    if (mm < 1) mm = 1
    if (mm > erfYukawaMaxM) mm = erfYukawaMaxM

    nYukawa = nterm(mm)
    alphas(1:nYukawa) = betaTab(1:nYukawa, mm) * omega
    coeffs(1:nYukawa) = coefTab(1:nYukawa, mm)

  end subroutine getErfRangeSepYukawas

